/* bakey color to pixel layout color */
static void bc2pixel(bakey_color_t in, uint8_t *out, uint64_t layout) {

	out[3] = 0;
	switch (layout) {

		/* r8, g8, b8, x8 */
		case RK_VIDEO_LAYOUT_RGB24:
		case RK_VIDEO_LAYOUT_RGBX32:
			out[0] = (uint8_t)((in >> 16) & 0xff);
			out[1] = (uint8_t)((in >> 8) & 0xff);
			out[2] = (uint8_t)(in & 0xff);
			break;

		/* b8, g8, r8, x8 */
		case RK_VIDEO_LAYOUT_BGR24:
		case RK_VIDEO_LAYOUT_BGRX32:
			out[0] = (uint8_t)(in & 0xff);
			out[1] = (uint8_t)((in >> 8) & 0xff);
			out[2] = (uint8_t)((in >> 16) & 0xff);
			break;
	}
}

/* draw character */
static void draw_character(
		char ch,
		size_t dx, size_t dy,
		uint8_t *data,
		size_t stride,
		size_t depth_bytes,
		uint8_t pixel_bg[4],
		uint8_t pixel_fg[4]
) {
	uint8_t *src = font_data + (size_t)ch * 16;
	uint8_t *color;

	for (size_t y = 0; y < 16; y++) {
		for (size_t x = 0; x < 9; x++) {

			color = pixel_bg;
			if (x < 8 && (src[y] & (uint8_t)(1 << (7 - x))))
				color = pixel_fg;

			memcpy(
				data + (dy + y) * stride +
				(dx + x) * depth_bytes,
				color, depth_bytes
			);
		}
	}
}

/* update display */
#define SWAP_VALUES(a, b) ({\
		a ^= b;\
		b ^= a;\
		a ^= b;\
	})

static void update_display(void) {

	for (size_t y = 0; y < display.height; y++) {
		for (size_t x = 0; x < display.width; x++) {

			size_t position = y * display.width + x;

			if (position != context.position &&
			    position != context.damage.position &&
			    (x < context.damage.x || y < context.damage.y ||
			     x >= context.damage.x + context.damage.width ||
			     y >= context.damage.y + context.damage.height))
				continue;

			bakey_cell_t *cell = display.cells + position;

			char ch = (char)cell->character;
			if (cell->character >= 0x7f)
				ch = '?';

			size_t dx = x * 9;
			size_t dy = y * 16;

			/* determine colors */
			bakey_color_t background = cell->background;
			bakey_color_t foreground = cell->foreground;

			if (cell->style & BAKEY_STYLE_INVERSE)
				SWAP_VALUES(background, foreground);
			if (position == context.position)
				SWAP_VALUES(background, foreground);

			/* draw character */
			uint8_t pixel_bg[4], pixel_fg[4];

			bc2pixel(
				background, pixel_bg,
				fb_attributes.layout
			);
			bc2pixel(
				foreground, pixel_fg,
				fb_attributes.layout
			);

			draw_character(
				ch,
				dx, dy,
				(uint8_t *)fb_data,
				fb_attributes.stride,
				fb_attributes.depth_bytes,
				pixel_bg, pixel_fg
			);
		}
	}
}

/* write to tty */
static size_t tty_write(rk_tty_device_t *_, const char *buffer, size_t count) {

	size_t total = count;
	while (count) {

		while (count && write_buffer_size < sizeof(write_buffer))
			write_buffer[write_buffer_size++] = buffer[total - (count--)];

		if (bakey_update(&context) != BAKEY_RESULT_SUCCESS)
			rk_log_error("Bakey: %s", bakey_get_error());
	}

	if (context.display_updated)
		update_display();
	bakey_reset_damage(&context);

	return total - count;
}

/* initialize module */
static void module_init(void) {

	video_device = rk_device_class_video.first;
	if (!video_device) {

		rk_log_error("No video device available");
		return;
	}

	/* determine mode for output */
	rk_video_mode_t *modes;
	rk_video_output_t *outputs;
	size_t mode_count, output_count;

	rk_video_device_get_modes(video_device, &modes, &mode_count);
	rk_video_device_get_outputs(video_device, &outputs, &output_count);

	if (!output_count) {

		rk_log_error("No video outputs available");
		return;
	}
	rk_video_mode_t *mode = rk_video_pick_mode_for_output(
			outputs, modes, mode_count
	);
	if (!mode || !mode->layout) {

		rk_log_error("No appropriate or supported video mode available");
		return;
	}
	rk_log_debug(
		"Output: device=%s, id=%zu",
		video_device->name,
		outputs->id
	);
	rk_log_debug(
		"Mode: size=%zux%zu, depth=%zu, layout=%zu",
		mode->width, mode->height,
		mode->depth, mode->layout
	);

	/* map framebuffer */
	if (!rk_video_device_configure_output(
				video_device, outputs, mode
	    )) {

		rk_log_error("Can't configure video mode");
		return;
	}

	void *fb_physical = rk_video_device_get_framebuffer_address(
			video_device, outputs
	);
	rk_video_device_get_framebuffer_attributes(
			video_device, outputs,
			&fb_attributes
	);

	fb_data = rk_mmu_map(
			NULL, fb_physical,
			fb_attributes.width *
			fb_attributes.height *
			(mode->depth / 3),
			0
	);

	/* determine terminal size */
	size_t width = fb_attributes.width / 9;
	size_t height = fb_attributes.height / 16;

	display.width = width;
	display.height = height;
	display.cells = (bakey_cell_t *)malloc(
			width * height * sizeof(bakey_cell_t)
	);

	rk_log_debug(
		"Terminal: size=%zux%zu, layout=%llu",
		width, height,
		fb_attributes.layout
	);

	/* open bakey context */
	bakey_config.background = 0x000000;
	bakey_config.foreground = 0xaaaaaa;

	bakey_config.colors[0] = 0x000000;
	bakey_config.colors[8] = 0x555555;

	bakey_config.colors[1] = 0xaa0000;
	bakey_config.colors[9] = 0xff5555;

	bakey_config.colors[2] = 0x00aa00;
	bakey_config.colors[10] = 0x55ff55;

	bakey_config.colors[3] = 0xaa5500;
	bakey_config.colors[11] = 0xffff55;

	bakey_config.colors[4] = 0x0000aa;
	bakey_config.colors[12] = 0x5555ff;

	bakey_config.colors[5] = 0xaa00aa;
	bakey_config.colors[13] = 0xff55ff;

	bakey_config.colors[6] = 0x00aaaa;
	bakey_config.colors[14] = 0x55ffff;

	bakey_config.colors[7] = 0xaaaaaa;
	bakey_config.colors[15] = 0xffffff;

	if (bakey_open(&context) != BAKEY_RESULT_SUCCESS) {

		rk_log_error("Bakey: %s", bakey_get_error());
		return;
	}
	update_display();

	/* register device */
	tty.write = tty_write;

	rk_device_register(
			device,
			"tty0",
			"Framebuffer Console",
			&rk_device_class_tty
	);
}

/* deinitialize module */
static void module_fini(void) {

	rk_device_unregister(device);
	bakey_close(&context);
}
